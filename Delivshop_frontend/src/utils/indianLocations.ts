export const INDIAN_STATES: string[] = Object.keys(STATE_CITY_MAP).sort((a, b) =>
  a.localeCompare(b)
);

export function getAllIndianStates(): string[] {
  return INDIAN_STATES;
}

export function getCitiesForState(state: string): string[] {
  if (!state || !state.trim()) return [];
  const cleanState = state.trim().toLowerCase();
  const match = Object.keys(STATE_CITY_MAP).find(
    (s) => s.toLowerCase() === cleanState
  );
  return match ? STATE_CITY_MAP[match] : [];
}

export function getStateForCity(city: string): string | undefined {
  if (!city || !city.trim()) return undefined;
  const cleanCity = city.trim().toLowerCase();
  for (const [state, cities] of Object.entries(STATE_CITY_MAP)) {
    if (
      cities.some(
        (c) =>
          c.toLowerCase() === cleanCity ||
          c.toLowerCase().startsWith(cleanCity) ||
          cleanCity.startsWith(c.toLowerCase().split(' ')[0])
      )
    ) {
      return state;
    }
  }
  return undefined;
}

export function searchCities(
  query: string,
  stateFilter?: string
): LocationEntry[] {
  const q = query.trim().toLowerCase();
  const results: LocationEntry[] = [];

  const statesToSearch =
    stateFilter && stateFilter.trim() && STATE_CITY_MAP[stateFilter.trim()]
      ? [stateFilter.trim()]
      : Object.keys(STATE_CITY_MAP);

  for (const state of statesToSearch) {
    const cities = STATE_CITY_MAP[state] || [];
    for (const city of cities) {
      if (!q || city.toLowerCase().includes(q)) {
        results.push({ city, state });
      }
    }
  }

  // Sort: exact matches first, then startsWith, then alphabetical
  return results.sort((a, b) => {
    const aLower = a.city.toLowerCase();
    const bLower = b.city.toLowerCase();
    const aStarts = aLower.startsWith(q);
    const bStarts = bLower.startsWith(q);

    if (aStarts && !bStarts) return -1;
    if (!aStarts && bStarts) return 1;
    return a.city.localeCompare(b.city);
  });
}

export function searchStates(query: string): string[] {
  const q = query.trim().toLowerCase();
  return INDIAN_STATES.filter((s) => !q || s.toLowerCase().includes(q)).sort(
    (a, b) => {
      const aStarts = a.toLowerCase().startsWith(q);
      const bStarts = b.toLowerCase().startsWith(q);
      if (aStarts && !bStarts) return -1;
      if (!aStarts && bStarts) return 1;
      return a.localeCompare(b);
    }
  );
}

export function isValidState(state: string): boolean {
  if (!state || !state.trim()) return false;
  return INDIAN_STATES.some(
    (s) => s.toLowerCase() === state.trim().toLowerCase()
  );
}

/**
 * Checks if a city/village is valid.
 * Known cities in the dataset are validated against their state.
 * Any non-empty string (>= 2 characters) entered for a valid state is accepted as a valid village/town.
 */
export function isValidCity(city: string, state?: string): boolean {
  if (!city || city.trim().length < 2) return false;
  const cleanCity = city.trim().toLowerCase();

  // If state is given, verify state is valid first
  if (state && state.trim()) {
    // If it's a known city in this state, perfect
    const knownInState = (STATE_CITY_MAP[state.trim()] || []).some(
      (c) => c.toLowerCase() === cleanCity
    );
    if (knownInState) return true;

    // Check if the city belongs to a DIFFERENT known state (which would be an invalid combo)
    const otherState = getStateForCity(city);
    if (otherState && otherState.toLowerCase() !== state.trim().toLowerCase()) {
      // Belongs to a different state
      return false;
    }

    // Otherwise, treat as an accepted custom town/village within this state
    return true;
  }

  // If no state given, check if recognized or >= 2 chars
  return true;
}
